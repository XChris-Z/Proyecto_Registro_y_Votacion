-- 3. Tabla de Votos de Jurado
CREATE TABLE public.votos_jurado (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  jurado_id UUID REFERENCES public.perfiles(id) ON DELETE CASCADE NOT NULL,
  proyecto_id BIGINT REFERENCES public.proyectos(id) ON DELETE CASCADE NOT NULL,
  criterio_id BIGINT REFERENCES public.criterios_evaluacion(id) ON DELETE CASCADE NOT NULL,
  calificacion NUMERIC NOT NULL CHECK (calificacion >= 1 AND calificacion <= 10),
  fecha_voto TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL,
  
  -- Restricción UNIQUE para evitar doble voto por criterio en un proyecto
  UNIQUE (jurado_id, proyecto_id, criterio_id)
);

ALTER TABLE public.votos_jurado ENABLE ROW LEVEL SECURITY;
CREATE POLICY "Jurados pueden ver sus propios votos" ON public.votos_jurado FOR SELECT USING (auth.uid() = jurado_id);
-- Permitir lectura para todos temporalmente (útil si hay un panel de admin de resultados global)
CREATE POLICY "Permitir lectura general de votos_jurado" ON public.votos_jurado FOR SELECT USING (true);
