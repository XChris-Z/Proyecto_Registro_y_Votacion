-- 1. Tabla de Perfiles (extendiendo auth.users)
CREATE TABLE public.perfiles (
  id UUID REFERENCES auth.users(id) ON DELETE CASCADE PRIMARY KEY,
  rol TEXT NOT NULL DEFAULT 'jurado',
  nombre_completo TEXT,
  email TEXT,
  creado_en TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- Asegurarse de que el RLS (Row Level Security) permita al service_role o usuarios acceder
ALTER TABLE public.perfiles ENABLE ROW LEVEL SECURITY;
CREATE POLICY "Permitir lectura pública de perfiles" ON public.perfiles FOR SELECT USING (true);

-- 2. Tabla de Criterios de Evaluación
CREATE TABLE public.criterios_evaluacion (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre TEXT NOT NULL,
  descripcion TEXT,
  peso_porcentual NUMERIC, -- Opcional
  creado_en TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

ALTER TABLE public.criterios_evaluacion ENABLE ROW LEVEL SECURITY;
CREATE POLICY "Permitir lectura pública de criterios" ON public.criterios_evaluacion FOR SELECT USING (true);

